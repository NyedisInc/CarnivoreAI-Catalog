"""Fixtures that build a real catalog repository with real signatures.

NOTHING HERE IS A MOCK OF THE CRYPTOGRAPHY. The keypairs are generated by the
real ``minisign`` binary into a temporary directory at test time, and the
signatures are made by that binary too. A test that signed with the same code
that verifies would pass with both halves broken the same way.

NO PRIVATE KEY IS EVER COMMITTED. Every key lives for the length of one test
and dies with its ``tmp_path``. The keys are generated with ``-W``, so they
carry no password and nothing ever prompts on a machine with no terminal.

WHEN THE BINARY IS ABSENT THE TESTS SKIP, WITH A REASON THAT NAMES THE FIX.
A skip is not a pass and the run says so; this is the same posture the
product repo takes for the same reason.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

